        return [
            'label' => __('Save'),
            'class' => 'save primary',
            'class_name' => Container::SPLIT_BUTTON,
            'sort_order' => 90,
            'options' => $this->getOptions(),
            'data_attribute' => [
                'mage-init' => [
                    'buttonAdapter' => [
                        'actions' => [
                            [
                                'targetName' => 'scue_menu_banner_form.scue_menu_banner_form',
