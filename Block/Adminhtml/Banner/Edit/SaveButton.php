                            ]
                        ]
                    ]
                ]
            ],
        ];
    }

    /**
     * Retrieve options.
     *
     * @return array
     */
    private function getOptions(): array
    {
        return [
            [
                'id_hard' => 'save_and_close',
                'label' => __('Save & Close'),
                'data_attribute' => [
                    'mage-init' => [
                        'buttonAdapter' => [
                            'actions' => [
                                [
                                    'targetName' => 'scue_menu_banner_form.scue_menu_banner_form',
                                    'actionName' => 'save',
                                    'params' => [
                                        true
                                    ]
                                ]
                            ]
                        ]
                    ]
                ],
            ]
        ];
    }
}
